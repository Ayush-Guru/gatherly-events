create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text,
  role text not null default 'attendee' check (role in ('attendee', 'organizer', 'admin')),
  created_at timestamptz not null default now()
);

create table if not exists public.events (
  id text primary key,
  title text not null,
  category text not null,
  date timestamptz not null,
  end_date timestamptz,
  venue text not null,
  city text not null,
  type text not null default 'In person',
  price integer not null default 0,
  attendees integer not null default 0,
  capacity integer not null default 200,
  featured boolean not null default false,
  rating numeric not null default 5,
  image text not null,
  gallery jsonb not null default '[]'::jsonb,
  description text not null,
  long_description text not null default '',
  agenda jsonb not null default '[]'::jsonb,
  speakers jsonb not null default '[]'::jsonb,
  tags jsonb not null default '[]'::jsonb,
  organizer_id uuid references public.profiles(id),
  created_at timestamptz not null default now()
);

create table if not exists public.registrations (
  id text primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  event_id text not null references public.events(id) on delete cascade,
  name text not null,
  email text not null,
  phone text not null,
  attendees integer not null default 1 check (attendees between 1 and 8),
  ticket text not null default 'general',
  total integer not null default 0,
  transaction_id text not null,
  status text not null default 'Pending' check (status in ('Pending', 'Confirmed', 'Rejected', 'Cancelled')),
  payment_status text not null default 'manual_pending' check (payment_status in ('manual_pending', 'paid', 'rejected', 'demo')),
  created_at timestamptz not null default now(),
  unique(user_id, event_id)
);

create table if not exists public.saved_events (
  user_id uuid not null references auth.users(id) on delete cascade,
  event_id text not null references public.events(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (user_id, event_id)
);

create table if not exists public.reviews (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  event_id text not null references public.events(id) on delete cascade,
  rating integer not null check (rating between 1 and 5),
  body text,
  created_at timestamptz not null default now(),
  unique(user_id, event_id)
);

alter table public.profiles enable row level security;
alter table public.events enable row level security;
alter table public.registrations enable row level security;
alter table public.saved_events enable row level security;
alter table public.reviews enable row level security;

create policy "Public can view events" on public.events for select using (true);
create policy "Organizers manage their events" on public.events for all using (auth.uid() = organizer_id or exists (select 1 from public.profiles where id = auth.uid() and role in ('admin', 'organizer')));
create policy "Users view their registrations" on public.registrations for select using (auth.uid() = user_id);
create policy "Users create their registrations" on public.registrations for insert with check (auth.uid() = user_id);
create policy "Users cancel their registrations" on public.registrations for update using (auth.uid() = user_id);
create policy "Organizers review registrations" on public.registrations for select using (exists (select 1 from public.profiles where id = auth.uid() and role in ('admin', 'organizer')));
create policy "Organizers approve registrations" on public.registrations for update using (exists (select 1 from public.profiles where id = auth.uid() and role in ('admin', 'organizer')));
create policy "Users manage saved events" on public.saved_events for all using (auth.uid() = user_id) with check (auth.uid() = user_id);
create policy "Public can view reviews" on public.reviews for select using (true);
create policy "Users manage their reviews" on public.reviews for all using (auth.uid() = user_id) with check (auth.uid() = user_id);

create or replace function public.handle_new_user() returns trigger language plpgsql security definer set search_path = public as $$
begin insert into public.profiles (id, full_name) values (new.id, new.raw_user_meta_data->>'full_name'); return new; end; $$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users for each row execute procedure public.handle_new_user();

create or replace function public.sync_event_attendees() returns trigger language plpgsql security definer set search_path = public as $$
begin
  if TG_OP = 'INSERT' and new.status = 'Confirmed' then
    update public.events set attendees = attendees + new.attendees where id = new.event_id;
  elsif TG_OP = 'UPDATE' and old.status <> 'Confirmed' and new.status = 'Confirmed' then
    update public.events set attendees = attendees + new.attendees where id = new.event_id;
  elsif TG_OP = 'UPDATE' and old.status <> 'Cancelled' and new.status = 'Cancelled' then
    update public.events set attendees = greatest(0, attendees - old.attendees) where id = old.event_id;
  end if;
  return new;
end; $$;

drop trigger if exists on_registration_attendees on public.registrations;
create trigger on_registration_attendees after insert or update of status on public.registrations for each row execute procedure public.sync_event_attendees();

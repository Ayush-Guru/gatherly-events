begin
  if TG_OP = 'INSERT' and new.status = 'Confirmed' then
    update public.events set attendees = attendees + new.attendees where id = new.event_id;
  elsif TG_OP = 'UPDATE' and old.status <> 'Confirmed' and new.status = 'Confirmed' then
